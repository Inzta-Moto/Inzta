// F-016 design.md §20: full port of the Design System bundle.css into app/(v2)/v2-components.css.
// Usage: node scripts/port-v2-css.mjs [designRepo] [--check]
// --check only reports classes used by the canvas artboards that no ported rule styles (task A2 done-when).
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const check = args.includes('--check');
const repo = args.find(a => !a.startsWith('--')) || 'D:/Projects/inzta-web-design';
const D = path.join(repo, 'claude-design');
const out = path.join('app', '(v2)', 'v2-components.css');

function blocks(src) {
  const list = [];
  let i = 0;
  while (i < src.length) {
    while (i < src.length && /\s/.test(src[i])) i++;
    if (i >= src.length) break;
    if (src.startsWith('/*', i)) {
      const end = src.indexOf('*/', i) + 2;
      list.push({ type: 'comment', text: src.slice(i, end) });
      i = end;
      continue;
    }
    if (src.startsWith('@import', i)) {
      // A semicolon inside the url() would end a naive match, so skip to the closing parenthesis first.
      const close = src.indexOf(')', i);
      i = src.indexOf(';', close) + 1;
      continue;
    }
    const open = src.indexOf('{', i);
    const head = src.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (depth) {
      if (src[j] === '{') depth++;
      else if (src[j] === '}') depth--;
      j++;
    }
    list.push({ type: head.startsWith('@') ? 'at' : 'rule', head, body: src.slice(open + 1, j - 1) });
    i = j;
  }
  return list;
}

// The :focus-within dropdown selectors open a menu on focus alone; SiteNav drives data-open instead (D-5).
const dropFocusWithin = head => head.split(',').map(s => s.trim()).filter(s => !/\.iz-navdd:focus-within/.test(s));

function port(list, indent = '') {
  const res = [];
  for (const b of list) {
    if (b.type === 'comment') continue;
    if (b.type === 'rule') {
      const parts = dropFocusWithin(b.head);
      if (!parts.length) continue;
      let body = b.body.trim();
      // .iz-page spans the viewport on the site, so its container declaration is dropped with the @container queries.
      if (parts.join(', ') === '.iz-page') body = body.replace(/container:[^;]+;\s*/, '');
      res.push(`${indent}${parts.join(', ')} { ${body} }`);
    } else if (b.head.startsWith('@keyframes')) {
      res.push(`${indent}${b.head} {${b.body}}`);
    } else {
      const head = b.head.replace(/^@container iz\s*/, '@media ');
      const inner = port(blocks(b.body), indent + '  ');
      if (inner.length) res.push(`${indent}${head} {\n${inner.join('\n')}\n${indent}}`);
    }
  }
  return res;
}

const bundle = fs.readFileSync(path.join(D, 'ds/project/components/bundle.css'), 'utf8');
const css = port(blocks(bundle)).join('\n') + '\n';

if (check) {
  const canvas = JSON.parse(fs.readFileSync(path.join(D, 'canvas/project/canvas.json'), 'utf8'));
  const files = fs.readdirSync(path.join(D, 'canvas/project')).filter(f => f.endsWith('.dc.html'));
  const used = new Set();
  for (const f of files) {
    const html = fs.readFileSync(path.join(D, 'canvas/project', f), 'utf8');
    for (const m of html.matchAll(/class="([^"]+)"/g)) m[1].split(/\s+/).filter(c => /^(iz-|t-)/.test(c)).forEach(c => used.add(c));
  }
  const ported = fs.readFileSync(out, 'utf8') + fs.readFileSync(path.join('app', '(v2)', 'v2-tokens.css'), 'utf8');
  const styled = new Set([...ported.matchAll(/\.((?:iz|t)-[a-zA-Z0-9_-]+)/g)].map(m => m[1]));
  const missing = [...used].filter(c => !styled.has(c)).sort();
  console.log(`${files.length} artboard files; ${used.size} classes used; ${missing.length} without a ported rule`);
  if (missing.length) console.log(missing.join('\n'));
  process.exit(0);
}

const header = `/* INZTA v2 components (F-016). Full port of inzta-web-design claude-design/ds/project/components/bundle.css
   (design.md §20), generated by scripts/port-v2-css.mjs: @container iz replaced by @media because .iz-page spans the
   viewport, @import removed (fonts come from next/font), :focus-within dropdown selectors removed. Do not edit by hand;
   fixes and states the canvas does not cover go to v2-overrides.css or v2-<area>.css. */
`;
fs.writeFileSync(out, header + css);
console.log(`wrote ${out}: ${css.length} bytes from ${bundle.length}`);
