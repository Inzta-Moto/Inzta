// F-016 fit (Sehan, 2026-10-29: "cocok untuk 100% views, jangan terlihat seperti nge-zoom"). The design is drawn at
// 1440 px; laptops with OS scaling show about 1280 CSS px, where every fixed size looks about 12% too big. This
// generates app/(v2)/v2-fit.css: between 1024 and 1439 px one design pixel becomes var(--u) = 100vw / 1440, applied to
// the spacing and size tokens and to every fixed font-size in the v2 CSS, with floors so nothing gets unreadably small.
// Usage: node scripts/gen-v2-fit.mjs [--check]   (--check fails when the committed file is out of date)
import fs from 'node:fs';
import path from 'node:path';

const dir = path.join('app', '(v2)');
const out = path.join(dir, 'v2-fit.css');
const SOURCES = ['v2-tokens.css', 'v2-components.css', 'v2-overrides.css', 'v2-ui.css', 'v2-home.css', 'v2-about.css', 'v2-motor.css', 'v2-article.css', 'v2-article-body.css', 'v2-catalog.css', 'v2-product.css'];
// Already fluid in v2-overrides.css (clamp with a viewport-height limit); scaling them again would fight that rule.
const SKIP = new Set(['.t-display', '.t-h2-landing', '.t-lead', '.iz-gfeature h3', '.iz-rfeature blockquote', '.iz-page .t-display', '.iz-page .t-h2-landing', '.iz-page .t-lead', '.iz-page .iz-gfeature h3', '.iz-page .iz-rfeature blockquote']);
const MIN_PX = 13;
const FLOOR = 0.84;

const TOKENS = [
  ['--space-2', 8], ['--space-3', 12], ['--space-4', 16], ['--space-5', 20], ['--space-6', 24], ['--space-8', 32],
  ['--space-10', 40], ['--space-12', 48], ['--space-18', 72], ['--space-30', 120],
];
const SIZED = [
  ['--size-content', 1200, 960], ['--size-nav', 64, 56], ['--size-button', 56, 48], ['--size-tap', 48, 44], ['--size-chip', 40, 36],
];

function splitTop(head) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < head.length; i++) {
    if (head[i] === '(') depth++;
    else if (head[i] === ')') depth--;
    else if (head[i] === ',' && depth === 0) {
      parts.push(head.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(head.slice(start));
  return parts.map(p => p.trim()).filter(Boolean);
}

// A media block applies inside 1024–1439 unless it caps the width below 1024 or starts above 1439.
function appliesInRange(cond) {
  const max = cond.match(/max-width:\s*(\d+(?:\.\d+)?)px/);
  const min = cond.match(/min-width:\s*(\d+(?:\.\d+)?)px/);
  if (max && Number(max[1]) < 1024) return false;
  if (min && Number(min[1]) > 1439) return false;
  return !/prefers-reduced-motion:\s*reduce|print/.test(cond);
}

function rules(css) {
  const found = [];
  const src = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const walk = (s, ok) => {
    let j = 0;
    while (j < s.length) {
      const open = s.indexOf('{', j);
      if (open === -1) break;
      const head = s.slice(j, open).trim();
      let depth = 1;
      let k = open + 1;
      while (depth && k < s.length) {
        if (s[k] === '{') depth++;
        else if (s[k] === '}') depth--;
        k++;
      }
      const body = s.slice(open + 1, k - 1);
      if (head.startsWith('@media')) walk(body, ok && appliesInRange(head));
      else if (head.startsWith('@supports')) walk(body, ok);
      else if (ok && !head.startsWith('@')) {
        const size = body.match(/(?:^|;)\s*font-size:\s*(\d+(?:\.\d+)?)px\s*(?:;|$)/);
        if (size && Number(size[1]) >= MIN_PX) found.push({ selectors: splitTop(head), px: Number(size[1]) });
      }
      j = k;
    }
  };
  walk(src, true);
  return found;
}

const scoped = sel => (/^\.iz-page\b/.test(sel) ? `html ${sel}` : `html .iz-page ${sel}`);
const round = n => Math.round(n * 10) / 10;

const lines = [];
lines.push('/* Generated by scripts/gen-v2-fit.mjs from the v2 CSS; do not edit by hand. See the script for the why. */');
lines.push('@media (min-width: 1024px) and (max-width: 1439.98px) {');
const tokenDecls = [
  '--u: calc(100vw / 1440)',
  ...TOKENS.map(([name, px]) => `${name}: calc(${px} * var(--u))`),
  ...SIZED.map(([name, px, floor]) => `${name}: max(${floor}px, calc(${px} * var(--u)))`),
];
lines.push(`  .iz-page { ${tokenDecls.join('; ')}; }`);
const seen = new Set();
for (const file of SOURCES) {
  const p = path.join(dir, file);
  if (!fs.existsSync(p)) continue;
  for (const { selectors, px } of rules(fs.readFileSync(p, 'utf8'))) {
    const keep = selectors.filter(sel => !SKIP.has(sel) && !sel.includes('::'));
    if (!keep.length) continue;
    const key = `${keep.join(',')}|${px}`;
    if (seen.has(key)) continue;
    seen.add(key);
    lines.push(`  ${keep.map(scoped).join(', ')} { font-size: max(${round(px * FLOOR)}px, calc(${px} * var(--u))); }`);
  }
}
lines.push('}');
const css = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== css) {
    console.error(`${out} is out of date: run node scripts/gen-v2-fit.mjs`);
    process.exit(1);
  }
  console.log(`${out} ok`);
} else {
  fs.writeFileSync(out, css);
  console.log(`${out}: ${seen.size} font rules`);
}
